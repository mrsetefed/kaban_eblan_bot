def load_owl_links() -> list:
    """Прямые ссылки на гифки или картинки из media/taro_links.txt (по одной на строку, # начинает комментарий)."""
    try:
        text = OWL_LINKS_FILE.read_text(encoding="utf-8-sig")
    except FileNotFoundError:
        return []
    except Exception as e:
        logging.warning(f"Не удалось прочитать {OWL_LINKS_FILE.name}: {e}")
        return []
    links = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if media_kind(line):
            links.append(line)
        else:
            logging.warning(f"{OWL_LINKS_FILE.name}: ссылка пропущена (нужна прямая ссылка на .gif/.mp4/.jpg/.png): {line}")
    return list(dict.fromkeys(links))


OWL_LINKS = load_owl_links()


def draw_card(rng=random) -> dict:
    """Одна из 22 карт (прямая или перевёрнутая) или, с шансом 1 из 23, карта-пасхалка."""
    index = rng.randrange(len(MAJOR_ARCANA) + 1)
    if index == len(MAJOR_ARCANA):
        return {"owl": True}
    number, name, up_keys, up_text, rev_keys, rev_text = MAJOR_ARCANA[index]
    reversed_card = rng.random() < 0.5
    return {
        "owl": False,
        "number": number,
        "name": name,
        "reversed": reversed_card,
        "keys": rev_keys if reversed_card else up_keys,
        "text": rev_text if reversed_card else up_text,
    }


def format_card(name: str, card: dict) -> str:
    if card["owl"]:
        return (
            f"🔮 <b>{name}</b> тянет карту\n\n"
            f"🦉 <b>{OWL_TITLE}</b> 💀 худшая карта во всей колоде\n\n"
            f"<b>Общее трактование:</b> {OWL_TEXT}"
        )
    position = ", перевёрнутая 🔄" if card["reversed"] else ""
    return (
        f"🔮 <b>{name}</b> тянет карту\n\n"
        f"🃏 <b>{card['name']}</b> ({card['number']}){position}\n"
        f"<i>{card['keys']}</i>\n\n"
        f"<b>Общее трактование:</b> {card['text']}"
    )


async def edit_or_send(update: Update, message, text: str):
    try:
        await message.edit_text(text, parse_mode=ParseMode.HTML)
    except Exception as e:
        logging.warning(f"Не удалось отредактировать сообщение /taro: {e}")
        await update.message.reply_text(text, parse_mode=ParseMode.HTML)


async def show_card(update: Update, name: str, card: dict):
    message = await update.message.reply_text("🔮 Тасую колоду…")
    await asyncio.sleep(SHUFFLE_DELAY)
    await edit_or_send(update, message, format_card(name, card))


async def show_owl(update: Update, name: str, card: dict):
    text = format_card(name, card)
    owls = OWL_LINKS + media_store.stored("taro")  # ссылки из файла и то, что добавили через /media
    if owls:
        link = random.choice(owls)
        try:
            await send_media(update.message, link, caption=text, parse_mode=ParseMode.HTML)
            return
        except Exception as e:
            logging.warning(f"Не удалось отправить мемную сову {link}: {e}")

    message = await update.message.reply_text("🔮 Тасую колоду…")
    await asyncio.sleep(SHUFFLE_DELAY)
    for frame in OWL_FRAMES:
        try:
            await message.edit_text(frame)
        except Exception as e:
            logging.warning(f"Кадр анимации совы не отправился: {e}")
            break
        await asyncio.sleep(FRAME_DELAY)
    await edit_or_send(update, message, text)


async def taro(update: Update, context: ContextTypes.DEFAULT_TYPE):
    name = html.escape(update.effective_user.full_name)
    card = draw_card()
    runner = show_owl if card["owl"] else show_card
    # показ идёт в фоне, чтобы вебхук ответил Telegram сразу
    context.application.create_task(runner(update, name, card), update=update)
